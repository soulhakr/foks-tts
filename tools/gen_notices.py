"""Generate THIRD_PARTY_NOTICES.md from the installed packages' own metadata and license files.

Run it with the FOKS TTS Python environment (which has every locked package installed):
    "$HOME/Library/Application Support/FOKS-TTS/venv/bin/python" tools/gen_notices.py
Re-run whenever requirements/core.txt or requirements/optional-gpl-pronunciation.txt change.
"""
import hashlib, importlib.metadata as md, pathlib, re, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
norm = lambda n: re.sub(r"[-_.]+", "-", n).lower()

def requirement_names(path):
    return [norm(re.split(r"[=@ ]", l.strip())[0]) for l in open(path) if l.strip() and not l.startswith("#")]

core = requirement_names(ROOT / "requirements/core.txt")
optional = requirement_names(ROOT / "requirements/optional-gpl-pronunciation.txt")
dists = {norm(d.metadata["Name"]): d for d in md.distributions()}

def license_summary(d):
    m = d.metadata
    expr = m.get("License-Expression")
    if expr: return expr
    lic = (m.get("License") or "").strip()
    if lic and len(lic) < 80 and "\n" not in lic and lic.upper() != "UNKNOWN": return lic
    cl = [c.split("::")[-1].strip() for c in (m.get_all("Classifier") or []) if c.startswith("License")]
    return "; ".join(cl) or "see license text"

def homepage(d):
    m = d.metadata
    if m.get("Home-page"): return m["Home-page"]
    for u in (m.get_all("Project-URL") or []):
        k, _, v = u.partition(",")
        if k.strip().lower() in ("homepage", "home", "source", "repository", "source code", "github"): return v.strip()
    return ""

def license_files(d):
    out = []
    for f in d.files or []:
        if "dist-info" in str(f) and any(k in f.name.upper() for k in ("LICENSE", "LICENCE", "COPYING", "NOTICE")):
            try: out.append((f.name, d.read_text(f) or pathlib.Path(d.locate_file(f)).read_text(errors="replace")))
            except Exception: pass
    return out

groups = {}      # sha -> {"text": str, "pkgs": set}
rows, nofile = [], []
for grp, names in (("core", core), ("optional", optional)):
    for n in names:
        d = dists[n]
        files = license_files(d)
        rows.append((grp, n, d.version, license_summary(d), homepage(d)))
        if not files: nofile.append(n)
        for fname, text in files:
            t = text.strip()
            if not t: continue
            h = hashlib.sha256(t.encode()).hexdigest()
            groups.setdefault(h, {"text": t, "pkgs": set()})["pkgs"].add(f"{n} {d.version}")

# packages shipping no license file: attach to the Apache-2.0 text already collected when that is their license
apache = next((g for g in groups.values() if g["text"].lstrip().startswith("Apache License")), None)
unattached = []
for n in nofile:
    d = dists[n]
    if apache and ("apache" in license_summary(d).lower()):
        apache["pkgs"].add(f"{n} {d.version} (no license file shipped; Apache-2.0 per its metadata)")
    else:
        unattached.append(n)

L = []
w = L.append
w("# Third-party notices\n")
w("FOKS TTS itself is licensed under the MIT License (see [`LICENSE`](LICENSE)). It uses the third-party software")
w("and data listed below, each under its own license. This file is generated by `tools/gen_notices.py` from the")
w("packages' own metadata; do not edit it by hand.\n")
w("**What is and is not distributed.** This repository contains only FOKS TTS's own source. The packages below are")
w("downloaded by `install.sh` from their publishers (PyPI) and are not redistributed here. The optional GPL add-on")
w("(last section) is never bundled and is installed only if the user asks for it.\n")
w("## Runtime packages (default install)\n")
w("| Package | Version | License | Homepage |\n|---|---|---|---|")
for grp, n, v, lic, hp in rows:
    if grp == "core": w(f"| {n} | {v} | {lic} | {hp} |")
w("\nLicense texts for these packages are reproduced in full in the last section.\n")
w("## Model and data\n")
w("**Kokoro-82M** (`mlx-community/Kokoro-82M-bf16`, an MLX conversion of `hexgrad/Kokoro-82M`): Apache License 2.0.")
w("Downloaded by `install.sh`, not included in this repository. Per its model card, Kokoro was trained on permissive")
w("or public-domain audio, audio under licenses such as Apache and MIT, and synthetic audio from closed TTS")
w("providers, and the following datasets require attribution:\n")
w("- **Koniwa**, licensed CC BY 3.0: https://github.com/koniwa/koniwa")
w("- **SIWIS French Speech Synthesis Database**, licensed CC BY 4.0: https://datashare.ed.ac.uk/handle/10283/2353")
w("  (license text: https://datashare.ed.ac.uk/bitstream/handle/10283/2353/license_text)\n")
w("Kokoro is built on **StyleTTS 2** (architecture by `@yl4579` and co-authors, https://github.com/yl4579/StyleTTS2,")
w("MIT License) and uses an **ISTFTNet**-style vocoder. Model card: https://huggingface.co/hexgrad/Kokoro-82M\n")
w("**spaCy English pipeline `en_core_web_sm` 3.8.0** (Explosion, MIT License, https://spacy.io/models/en), used by the")
w("text normalizer. Per its model card it was trained from OntoNotes 5 (https://catalog.ldc.upenn.edu/LDC2013T19),")
w("the ClearNLP constituent-to-dependency conversion (Emory University) and WordNet 3.0 (Princeton University,")
w("https://wordnet.princeton.edu/).\n")
w("## Obtained or used but not distributed\n")
w("- **Python 3.13** (a uv-managed CPython build), downloaded at install time; Python Software Foundation License.")
w("- **uv** (Astral), used by the installer; MIT or Apache-2.0.")
w("- **Apple system frameworks** (AppKit, SwiftUI, Vision, ScreenCaptureKit, AVFoundation, ApplicationServices) and")
w("  SF Symbols names, used through the macOS SDK on the user's own Mac.")
w("- **Gemma 3** is not part of FOKS TTS. The experimental `screen_to_speech.sh` script can use a copy the user")
w("  already has locally; Gemma is distributed under Google's Gemma Terms of Use, which this project does not grant.\n")
w("## Optional GPL add-on (not distributed with FOKS TTS)\n")
w("These packages are installed only if the user presses *Install* under *Settings > Extended pronunciation*, which")
w("shows a license notice and asks for consent. They are separate works under the GNU General Public License and are")
w("fetched directly from PyPI; FOKS TTS does not include or redistribute them.\n")
w("| Package | Version | License | Homepage |\n|---|---|---|---|")
for grp, n, v, lic, hp in rows:
    if grp == "optional": w(f"| {n} | {v} | {lic} | {hp} |")
w("\n- `phonemizer-fork` is GPL-3.0-or-later.")
w("- `espeakng-loader` bundles the **eSpeak NG** library and data, which are GPL-3.0 (https://github.com/espeak-ng/espeak-ng).")
w("  The package itself declares no license in its metadata; treat the whole bundle as GPL-3.0.")
w("- Source for these packages is available from their PyPI project pages (sdists) and repositories above.\n")
w("## License texts\n")
for g in sorted(groups.values(), key=lambda g: sorted(g["pkgs"])[0].lower()):
    pk = sorted(g["pkgs"], key=str.lower)
    w("### " + (", ".join(p.split(" ")[0] for p in pk[:6]) + (f" and {len(pk) - 6} more" if len(pk) > 6 else "")))
    w("Applies to: " + "; ".join(pk) + "\n")
    w("````text\n" + g["text"] + "\n````\n")
if unattached:
    w("### Packages without a license file\n")
    w("No license file is shipped by: " + ", ".join(unattached) + ". See their homepages above.\n")
pathlib.Path(ROOT / "THIRD_PARTY_NOTICES.md").write_text("\n".join(L))
print(f"wrote THIRD_PARTY_NOTICES.md: {len([r for r in rows if r[0]=='core'])} runtime + "
      f"{len([r for r in rows if r[0]=='optional'])} optional packages, {len(groups)} distinct license texts, "
      f"{len(unattached)} without a license file")
